#!/usr/bin/env python3
"""Generate garmin/watch/test/Vectors.mc from shared/engine-vectors.json.

The watch test suite cannot parse JSON - there is no JSON library in Monkey C and
writing one for fixtures would test the parser rather than the engine - so the
same cases are emitted as Monkey C literals. The JSON stays the single source of
truth: this script only translates.

    python tools/gen_engine_vectors.py           # rewrite Vectors.mc
    python tools/gen_engine_vectors.py --check   # exit 1 if it is out of date

Run --check in CI: it is the difference between "the watch tests pass" and "the
watch tests pass against the same cases the phone runs".
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "shared" / "engine-vectors.json"
TARGET = ROOT / "garmin" / "watch" / "test" / "Vectors.mc"

# Field names the schema uses, emitted as Symbols. Everything else in the file is
# a data map (muscle id -> share, exercise id -> score) and must be a String key:
# the engine looks those up with a String, and a Symbol key would silently miss.
SCHEMA_KEYS = {
    "name", "weight", "reps", "rir", "expect", "spec", "history", "seedKg",
    "expectWeight", "expectReps", "weeklyMuscleSets", "everTrained", "specs",
    "sets", "now", "load", "expectOrder", "expectScores", "base", "peakHr",
    "currentHr", "restingHr", "ceiling", "expectSeconds", "expectReady",
    "bodyKg", "bodyweightFraction", "pushUpReps", "squatReps", "expectE1rm",
    "seeds", "id", "lo", "hi", "inc", "minW", "rest", "pattern", "bw", "ts",
    "primary", "secondary",
}

SECTIONS = [
    "e1rm", "nextLoad", "recommendedSets", "muscleLoad",
    "recovery", "rank", "rest", "seed",
]

# One Monkey C function per section, so a failing section names itself.
FUNCTION_NAMES = {
    "e1rm": "e1rm",
    "nextLoad": "nextLoad",
    "recommendedSets": "recommendedSets",
    "muscleLoad": "muscleLoad",
    "recovery": "recovery",
    "rank": "rank",
    "rest": "rest",
    "seed": "seed",
}


def escape(text: str) -> str:
    out = text.replace("\\", "\\\\").replace('"', '\\"')
    return out.replace("\n", "\\n")


def number(value: float | int) -> str:
    if isinstance(value, bool):
        raise TypeError("bool is not a number")
    if isinstance(value, int):
        return str(value)
    text = f"{value:.6f}".rstrip("0")
    if text.endswith("."):
        text += "0"
    # A Float literal in Monkey C must carry a decimal point, or the value
    # arrives as a 32-bit Number and every division truncates.
    if "." not in text:
        text += ".0"
    return text


def literal(value, path: str) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return number(value)
    if isinstance(value, str):
        return f'"{escape(value)}"'
    if isinstance(value, list):
        inner = ", ".join(literal(item, path) for item in value)
        return f"[{inner}]"
    if isinstance(value, dict):
        parts = []
        # The case name first: these lines are long, and a reader scanning the
        # generated file needs to know which case a line belongs to.
        items = list(value.items())
        items.sort(key=lambda kv: 0 if kv[0] == "name" else 1)
        for key, item in items:
            if key in SCHEMA_KEYS:
                rendered_key = f":{key}"
            else:
                if not isinstance(key, str):
                    raise TypeError(f"{path}: data map key {key!r} is not a string")
                # A data map is muscle id -> number or exercise id -> number.
                # Anything else means a schema field was forgotten above, which
                # would reach the watch as a String key and read as null.
                if isinstance(item, (dict, list)):
                    raise TypeError(
                        f"{path}: key {key!r} holds a {type(item).__name__}; "
                        "add it to SCHEMA_KEYS if it is part of the schema"
                    )
                rendered_key = f'"{escape(key)}"'
            parts.append(f"{rendered_key} => {literal(item, f'{path}.{key}')}")
        return "{ " + ", ".join(parts) + " }"
    raise TypeError(f"{path}: cannot emit {type(value).__name__}")


def render(vectors: dict) -> str:
    lines = [
        "// Generated by tools/gen_engine_vectors.py from shared/engine-vectors.json.",
        "// Do not edit by hand: change the JSON and regenerate, then commit both.",
        "",
        "using Toybox.Lang;",
        "",
        "module Vectors {",
        "",
        f"    const TOLERANCE = {number(float(vectors['tolerance']))};",
    ]

    for section in SECTIONS:
        cases = vectors.get(section) or []
        lines.append("")
        lines.append(f"    // {len(cases)} cases")
        lines.append(f"    function {FUNCTION_NAMES[section]}() {{")
        if not cases:
            lines.append("        return [] as Lang.Array<Lang.Dictionary>;")
        else:
            lines.append("        return [")
            for case in cases:
                lines.append(f"            {literal(case, section)},")
            lines.append("        ];")
        lines.append("    }")

    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    check_only = "--check" in argv
    if not SOURCE.exists():
        print(f"missing {SOURCE}", file=sys.stderr)
        return 2

    vectors = json.loads(SOURCE.read_text(encoding="utf-8"))
    generated = render(vectors)

    if check_only:
        if not TARGET.exists():
            print(f"{TARGET} does not exist; run tools/gen_engine_vectors.py", file=sys.stderr)
            return 1
        current = TARGET.read_text(encoding="utf-8")
        if current.replace("\r\n", "\n") != generated:
            print(
                f"{TARGET.relative_to(ROOT)} is stale: regenerate it from "
                "shared/engine-vectors.json",
                file=sys.stderr,
            )
            return 1
        print("Vectors.mc is up to date")
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    with open(TARGET, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(generated)

    counts = {section: len(vectors.get(section) or []) for section in SECTIONS}
    print(f"wrote {TARGET.relative_to(ROOT)}: " + ", ".join(f"{k} {v}" for k, v in counts.items()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
